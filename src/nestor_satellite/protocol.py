"""The values of the satellite protocol `nestor.satellite/1`: a device, what it can do, how it can be
paired, and the intents it receives.

They mirror the JSON Schemas shipped in `nestor_satellite/schemas/`, generated by the Nestor server.
"""

import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from enum import StrEnum
from importlib.metadata import version
from typing import Any

PROTOCOL = "nestor.satellite/1"
DISTRIBUTION = "nestor-satellite"  # this SDK's package

# Capabilities the core knows today; a driver may declare others (`family.feature`).
TEXT_INPUT = "text.input"  # it sends what a person typed
TEXT_DISPLAY = "text.display"  # it shows the assistant's words
AUDIO_CAPTURE = "audio.capture"
AUDIO_PLAYBACK = "audio.playback"
EXPRESSION = "expression.emotion"
HEAD_MOTION = "motion.head"
IDENTIFY = "device.identify"  # it can make itself noticed (blink, wiggle, chime): an aid, never a proof
UPDATE = "device.update"  # it installs a newer version of its own software, on a person's request
PERSON_DETECTION = "vision.person_detection"
SPEECH_ACTIVITY = "audio.speech_activity"

_SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")
_CAPABILITY = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$")


class ProtocolError(ValueError):
    """Something that does not follow `nestor.satellite/1`."""


class Behavior(StrEnum):
    IDLE = "idle"
    LISTENING = "listening"
    THINKING = "thinking"
    SPEAKING = "speaking"


class Expression(StrEnum):
    JOY = "joy"
    SIGH = "sigh"
    THOUGHTFUL = "thoughtful"
    WHISPER = "whisper"
    EXCITED = "excited"
    AHEM = "ahem"


class UpdateState(StrEnum):
    """Where the device's own software stands (`update.status`)."""

    CURRENT = "current"  # nothing newer at its source
    AVAILABLE = "available"  # a newer version can be installed
    INSTALLING = "installing"  # it installs that version, then starts again on it
    FAILED = "failed"  # that version did not install or did not start: it runs the one it ran


class PairingMethod(StrEnum):
    """How a person can pair a device. The device declares those it supports; the person picks one."""

    DISPLAY = "device_code.display"  # it shows its device code on a screen
    SPEECH = "device_code.speech"  # it says its device code aloud
    INPUT = "enrollment.input"  # an enrollment code can be typed on it
    PROVISIONING = "enrollment.provisioning"  # a pairing URI or code is set in its configuration
    QR = "enrollment.qr"  # it scans the QR code of a pairing URI

    @property
    def enrollment(self) -> bool:
        """Whether the proof is an enrollment code given to the device (else a device code it presents)."""
        return self.value.startswith("enrollment.")


@dataclass(frozen=True, slots=True)
class Device:
    """`id`, `room` and `brand` are lowercase slugs: they end up in addresses (`voice:salon`)."""

    id: str
    model: str
    room: str
    brand: str | None = None  # its maker, e.g. "pollen-robotics"

    def __post_init__(self) -> None:
        for name, value in (("id", self.id), ("room", self.room), ("brand", self.brand)):
            if value is not None and not _SLUG.match(value):
                raise ProtocolError(f"device {name} {value!r} must be a lowercase slug (a-z, 0-9, - and _)")
        if not 0 < len(self.model) <= 64:
            raise ProtocolError("device model must be 1 to 64 characters")


@dataclass(frozen=True, slots=True)
class Software:
    """What the device runs: its package, as named where it is installed from, and its version."""

    name: str
    version: str

    def __post_init__(self) -> None:
        if not 0 < len(self.name) <= 64 or not 0 < len(self.version) <= 64:
            raise ProtocolError("a software name and version are 1 to 64 characters")

    @classmethod
    def of(cls, distribution: str) -> "Software":
        """An installed Python package, at the version installed."""
        return cls(distribution, version(distribution))


@dataclass(frozen=True, slots=True)
class Capability:
    name: str
    params: Mapping[str, Any] = field(default_factory=dict)  # e.g. {"formats": ["opus/48000"]}

    def __post_init__(self) -> None:
        if not _CAPABILITY.match(self.name) or "name" in self.params:
            raise ProtocolError(f"invalid capability {self.name!r}: expected 'family.feature'")


@dataclass(frozen=True, slots=True)
class Manifest:
    """What the device says about itself. A `Satellite` sets `pairing_methods`, and the text, audio and
    update capabilities, from what it was given: a driver declares the others only. `software` is this
    SDK unless the driver names its own package (`Software.of("nestor-reachy")`)."""

    device: Device
    capabilities: tuple[Capability, ...] = ()
    pairing_methods: tuple[PairingMethod, ...] = (PairingMethod.PROVISIONING,)
    software: Software = field(default_factory=lambda: Software.of(DISTRIBUTION))

    def __post_init__(self) -> None:
        if len({c.name for c in self.capabilities}) != len(self.capabilities):
            raise ProtocolError("a capability is declared twice")
        if not self.pairing_methods or len(set(self.pairing_methods)) != len(self.pairing_methods):
            raise ProtocolError("a manifest lists at least one pairing method, each once")

    @classmethod
    def of(cls, device: Device, *names: str) -> "Manifest":
        return cls(device, tuple(Capability(n) for n in names))

    @property
    def names(self) -> frozenset[str]:
        return frozenset(c.name for c in self.capabilities)

    def to_json(self) -> dict[str, Any]:
        device = {"id": self.device.id, "model": self.device.model, "room": self.device.room}
        return {
            "protocol": PROTOCOL,
            "device": device | ({"brand": self.device.brand} if self.device.brand else {}),
            "software": {"name": self.software.name, "version": self.software.version},
            "capabilities": [{"name": c.name, **c.params} for c in self.capabilities],
            "pairing_methods": [m.value for m in self.pairing_methods],
        }
